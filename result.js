let marks = 75;

if (marks >= 80) {
  console.log('Your Grade: A+');
} else if (marks <= 79 && marks >= 70) {
  console.log('Your Grade: A');
} else if (marks <= 69 && marks >= 60) {
  console.log('Your Grade: B');
} else if (marks <= 59 && marks >= 50) {
  console.log('Your Grade: C');
} else {
  console.log('Fail');
}
